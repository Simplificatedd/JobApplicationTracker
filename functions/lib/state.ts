import type { StorageSnapshot } from "../../src/storage/StorageAdapter";
import {
  CloudSnapshotSizeError,
  D1_MAX_ROW_BYTES,
  serializeCloudSnapshot,
  utf8ByteLength,
} from "../../src/storage/snapshotSize";
import { HttpError } from "./http";
import { hasValidDocumentReferences, rethrowDocumentConflict } from "./documentLifecycle";
import type {
  AuthenticatedUser,
  CloudStateEnvelope,
  SaveStateRequest,
} from "./types";

// Transport bound, separate from the smaller persisted snapshot/row budget.
const MAX_STATE_REQUEST_BYTES = 5 * 1024 * 1024;
export const MAX_TOTAL_SNAPSHOT_BYTES = 512 * 1024 * 1024;

interface StateRow {
  revision: number;
  snapshot_json: string;
  updated_at: string;
}

interface StateUsageRow {
  used_bytes: number | string | null;
}

export function requireAvailableSnapshotQuota(
  usedBytes: number,
  incomingBytes: number,
) {
  if (usedBytes + incomingBytes > MAX_TOTAL_SNAPSHOT_BYTES) {
    throw new HttpError(
      507,
      "Cloud tracker data has reached its account safety limit.",
    );
  }
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isStorageSnapshot(value: unknown): value is StorageSnapshot {
  if (!isRecord(value)) {
    return false;
  }

  return (
    Array.isArray(value.activities) &&
    Array.isArray(value.applications) &&
    Array.isArray(value.contacts) &&
    Array.isArray(value.coverLetters) &&
    Array.isArray(value.interviews) &&
    (value.assessments === undefined || Array.isArray(value.assessments)) &&
    (typeof value.dataVersion !== "number" ||
      value.dataVersion < 3 ||
      Array.isArray(value.assessments)) &&
    Array.isArray(value.resumes) &&
    isRecord(value.analyticsSettings) &&
    isRecord(value.notificationState) &&
    isRecord(value.settings) &&
    (value.tablePreferences === null || isRecord(value.tablePreferences))
  );
}

export function parseSaveStateRequest(text: string): SaveStateRequest {
  if (utf8ByteLength(text) > MAX_STATE_REQUEST_BYTES) {
    throw new HttpError(413, "The cloud save request exceeds the 5 MiB transport limit.");
  }

  let value: unknown;

  try {
    value = JSON.parse(text);
  } catch {
    throw new HttpError(400, "The cloud snapshot is not valid JSON.");
  }

  if (!isRecord(value) || !isRecord(value.snapshot)) {
    throw new HttpError(400, "The cloud snapshot has an invalid shape.");
  }

  value.snapshot.coverLetters ??= [];

  if (!isStorageSnapshot(value.snapshot) || !hasValidDocumentReferences(value.snapshot)) {
    throw new HttpError(400, "The cloud snapshot has an invalid shape.");
  }

  if (
    value.baseRevision !== null &&
    (!Number.isInteger(value.baseRevision) || Number(value.baseRevision) < 1)
  ) {
    throw new HttpError(400, "The base revision is invalid.");
  }

  return {
    baseRevision: value.baseRevision as number | null,
    snapshot: value.snapshot,
  };
}

export async function getCloudState(
  database: D1Database,
  ownerId: string,
): Promise<CloudStateEnvelope | null> {
  const row = await database
    .prepare(
      "SELECT revision, snapshot_json, updated_at FROM tracker_state WHERE owner_id = ?",
    )
    .bind(ownerId)
    .first<StateRow>();

  if (!row) {
    return null;
  }

  const snapshot = JSON.parse(row.snapshot_json) as StorageSnapshot;

  return {
    revision: row.revision,
    snapshot: { ...snapshot, coverLetters: snapshot.coverLetters ?? [] },
    updatedAt: row.updated_at,
  };
}

export async function saveCloudState(
  database: D1Database,
  user: AuthenticatedUser,
  input: SaveStateRequest,
): Promise<CloudStateEnvelope> {
  const timestamp = new Date().toISOString();
  let serialized: ReturnType<typeof serializeCloudSnapshot>;
  try {
    serialized = serializeCloudSnapshot(input.snapshot);
  } catch (error) {
    if (error instanceof CloudSnapshotSizeError) throw new HttpError(413, error.message);
    throw error;
  }
  // Six SQLite serial-type varints plus the header-length varint need at most
  // 63 bytes. Reserve 64, an eight-byte revision, and both ISO timestamps.
  // created_at is also generated by this API and has the same ISO byte length.
  const rowBytes = serialized.bytes + utf8ByteLength(user.id) +
    utf8ByteLength(user.email) + 2 * utf8ByteLength(timestamp) + 64 + 8;
  if (rowBytes > D1_MAX_ROW_BYTES) {
    throw new HttpError(413, "Tracker data and account metadata exceed the cloud row limit. Export a backup, then reduce tracker data before saving again. Your existing cloud data was not changed.");
  }
  const snapshotJson = serialized.json;
  const usage = await database
    .prepare(
      `SELECT COALESCE(SUM(LENGTH(CAST(snapshot_json AS BLOB))), 0) AS used_bytes
       FROM tracker_state
       WHERE owner_id <> ?`,
    )
    .bind(user.id)
    .first<StateUsageRow>();
  requireAvailableSnapshotQuota(
    Number(usage?.used_bytes ?? 0),
    serialized.bytes,
  );

  if (input.baseRevision === null) {
    const result = await database
      .prepare(
        `INSERT OR IGNORE INTO tracker_state
          (owner_id, owner_email, revision, snapshot_json, created_at, updated_at)
         VALUES (?, ?, 1, ?, ?, ?)`,
      )
      .bind(user.id, user.email, snapshotJson, timestamp, timestamp)
      .run().catch(rethrowDocumentConflict);

    if ((result.meta.changes ?? 0) > 0) {
      return { revision: 1, snapshot: input.snapshot, updatedAt: timestamp };
    }
  } else {
    const result = await database
      .prepare(
        `UPDATE tracker_state
         SET owner_email = ?, revision = revision + 1, snapshot_json = ?, updated_at = ?
         WHERE owner_id = ? AND revision = ?
           AND COALESCE(json_extract(snapshot_json, '$.dataVersion'), 1) <= ?`,
      )
      .bind(
        user.email,
        snapshotJson,
        timestamp,
        user.id,
        input.baseRevision,
        input.snapshot.dataVersion ?? 1,
      )
      .run().catch(rethrowDocumentConflict);

    if ((result.meta.changes ?? 0) > 0) {
      return {
        revision: input.baseRevision + 1,
        snapshot: input.snapshot,
        updatedAt: timestamp,
      };
    }
  }

  const current = await getCloudState(database, user.id);
  if (
    current &&
    (current.snapshot.dataVersion ?? 1) > (input.snapshot.dataVersion ?? 1)
  ) {
    throw new HttpError(
      409,
      "This workspace uses a newer data format. Refresh or update the tracker before saving.",
    );
  }
  throw new CloudConflictError(current);
}

export class CloudConflictError extends HttpError {
  constructor(public readonly current: CloudStateEnvelope | null) {
    super(409, "Cloud data changed in another session.");
  }
}
